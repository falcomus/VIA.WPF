namespace VIA.WPF.Icons;

#region ### Enum XIconPack ###
/// <summary>
/// Defines the icon pack used by <see cref="XIcon"/>.
/// </summary>
public enum XIconPack
{
    /// <summary>
    /// Uses MahApps Material Design icons.
    /// </summary>
    MaterialDesign,

    /// <summary>
    /// Uses MahApps Material icons.
    /// </summary>
    Material,

    /// <summary>
    /// Uses MahApps Bootstrap icons.
    /// </summary>
    BootstrapIcons,

    /// <summary>
    /// Uses MahApps Font Awesome icons.
    /// </summary>
    FontAwesome,

    /// <summary>
    /// Uses MahApps Font Awesome 6 icons.
    /// </summary>
    FontAwesome6,

    /// <summary>
    /// Uses MahApps Modern icons.
    /// </summary>
    Modern,

    /// <summary>
    /// Uses MahApps Phosphor icons.
    /// </summary>
    PhosphorIcons,

    /// <summary>
    /// Uses MahApps File icons.
    /// </summary>
    FileIcons
}
#endregion