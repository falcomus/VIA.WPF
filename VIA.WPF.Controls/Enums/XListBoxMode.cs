namespace VIA.WPF.Controls;

#region ### Enum XListBoxMode ###
/// <summary>
/// Defines the visual presentation mode of an <see cref="XListBox"/>.
/// </summary>
public enum XListBoxMode
{
    /// <summary>
    /// Uses the regular navigation surface style.
