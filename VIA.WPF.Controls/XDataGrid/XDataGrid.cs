    #region ### Private Methods (Shared Helpers) ###
    private void OnPropertyChanged([CallerMemberName] string? propertyName = null)
    {
        this.PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(propertyName));
    }

    private void AttachToItemsView()
    {
        ICollectionView? newView = this.ResolveDisplayedItemsView();

        if (!ReferenceEquals(this._itemsView, newView))
        {
            if (this._itemsView is not null)
            {
                this._itemsView.Filter = null;
            }

            this._itemsView = newView;
        }

        if (this._itemsView is not null)
        {
            Predicate<object>? newFilter = this.HasAnyActiveFilter() ? this._filterPredicate : null;

            if (!ReferenceEquals(this._itemsView.Filter, newFilter))
            {
                this._itemsView.Filter = newFilter;
            }
        }
    }

    private ICollectionView? ResolveDisplayedItemsView()
    {
        if (base.ItemsSource is not null)
        {
            return CollectionViewSource.GetDefaultView(base.ItemsSource);
        }

        return CollectionViewSource.GetDefaultView(this.Items);
    }

    private static IEnumerable? ExtractRawItemsSource(IEnumerable? itemsSource)
    {
        return itemsSource switch
        {
            null => null,
            CollectionView view => view.SourceCollection,
            CollectionViewSource source => source.Source as IEnumerable,
            _ => itemsSource
        };
    }

    private string GetColumnKey(DataGridColumn column)
    {
        if (this.IsActionColumn(column))
        {
            return string.Empty;
        }

        if (!string.IsNullOrWhiteSpace(column.SortMemberPath))
        {
            return column.SortMemberPath;
        }

        if (column is DataGridBoundColumn boundColumn &&
            boundColumn.Binding is Binding binding &&
            binding.Path is not null &&
            !string.IsNullOrWhiteSpace(binding.Path.Path))
        {
            return binding.Path.Path;
        }

        return column.Header?.ToString() ?? string.Empty;
    }

    private static bool IsSamePropertyPath(string firstPropertyName, string secondPropertyName)
    {
        return string.Equals(firstPropertyName, secondPropertyName, StringComparison.Ordinal);
    }

    internal static T? FindVisualParent<T>(DependencyObject? source)
        where T : DependencyObject
    {
        DependencyObject? current = source;

        while (current is not null)
        {
            if (current is T result)
            {
                return result;
            }

            current = GetParent(current);
        }

        return null;
    }

    private static DependencyObject? GetParent(DependencyObject source)
    {
        return source is Visual or Visual3D
            ? VisualTreeHelper.GetParent(source) ?? LogicalTreeHelper.GetParent(source)
            : LogicalTreeHelper.GetParent(source);
    }
