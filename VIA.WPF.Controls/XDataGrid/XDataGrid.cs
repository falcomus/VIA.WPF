    #region ### Protected Methods ###
    /// <inheritdoc />
    public override void OnApplyTemplate()
    {
        base.OnApplyTemplate();
        this.EnsureActionColumn();
        this.ApplyColumnDisplayMode();
    }

    /// <summary>
    /// Called when the items source changes.
    /// </summary>
    protected override void OnItemsSourceChanged(IEnumerable oldValue, IEnumerable newValue)
    {
        base.OnItemsSourceChanged(oldValue, newValue);

        this.CancelCurrentFilterItemsLoad();
        this._rawItemsSource = ExtractRawItemsSource(newValue);

        if (!this.IsLoaded)
        {
            return;
        }

        this.AttachToItemsView();
        this.EnsureActionColumn();
        this.ApplyColumnDisplayMode();
        this.EnsureDefinitionsAndSearchableColumns();
        this.InvalidateAllColumnFilterItems();
        this.RestorePersistedViewStateOrApplyInitialSort();
        this.RefreshFilters();

        if (this.IsLoaded)
        {
            this.PrewarmPropertyAccessorCache();
        }
    }

    /// <inheritdoc />
    protected override void OnSorting(DataGridSortingEventArgs eventArgs)
    {
        if (eventArgs.Column is not null && this.TryApplyUserSort(eventArgs.Column))
        {
            eventArgs.Handled = true;
            this.ScheduleViewStateStore();
            return;
        }

        base.OnSorting(eventArgs);

        this.ScheduleViewStateStore();
    }

    /// <inheritdoc />
    protected override void OnMouseDoubleClick(MouseButtonEventArgs e)
    {
        base.OnMouseDoubleClick(e);
        this.TryExecuteEditOnRowDoubleClick(e);
    }

    /// <inheritdoc />
    protected override void OnPreviewKeyDown(KeyEventArgs e)
    {
        if (this.TryExecuteKeyboardShortcut(e))
        {
            e.Handled = true;
            return;
        }

        base.OnPreviewKeyDown(e);
    }

