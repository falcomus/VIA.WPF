namespace VIA.WPF.Controls;

#region ### Enum XExpandDirection ###
/// <summary>
/// Defines the direction in which an <see cref="XExpander"/> expands.
/// </summary>
public enum XExpandDirection
{
    /// <summary>
    /// Expands downward.
    /// </summary>
    Down,

    /// <summary>
    /// Expands upward.
    /// </summary>
    Up,

    /// <summary>
    /// Expands to the left.
    /// </summary>
    Left,

    /// <summary>
    /// Expands to the right.
    /// </summary>
    Right,
}
#endregion
