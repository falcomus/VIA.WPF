namespace VIA.WPF.Controls;

#region ### Enum XTabHeaderAppearance ###
/// <summary>
/// Defines the visual appearance of tab headers.
/// </summary>
public enum XTabHeaderAppearance
{
    /// <summary>
    /// Renders standard tab headers.
    /// </summary>
    Default,

    /// <summary>
    /// Renders compact segmented headers.
    /// </summary>
    Segmented,

    /// <summary>
    /// Renders headers with a visible underline.
    /// </summary>
    Underlined,
}
#endregion
