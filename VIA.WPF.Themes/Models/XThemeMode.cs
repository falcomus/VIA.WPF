namespace VIA.WPF.Themes;

#region ### Enum XThemeMode ###
/// <summary>
/// Defines the active display mode of an <see cref="XTheme"/>.
/// </summary>
public enum XThemeMode
{
    /// <summary>
    /// Uses the theme's light resources.
    /// </summary>
    Light = 0,

    /// <summary>
    /// Uses the theme's dark resources.
    /// </summary>
    Dark = 1
}
#endregion